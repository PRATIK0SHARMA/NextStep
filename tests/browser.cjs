const {chromium}=require('playwright');
(async()=>{
const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_EXECUTABLE?{executablePath:process.env.CHROMIUM_EXECUTABLE}:{}),args:['--no-sandbox','--disable-gpu','--disable-software-rasterizer']});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8000');await page.locator('#sample').waitFor();
await page.screenshot({path:'docs/screenshots/start.png',fullPage:true});
await page.locator('#sample').click();await page.getByRole('button',{name:'Find available appointments'}).click();
await page.locator('.provider').first().waitFor();
await page.screenshot({path:'docs/screenshots/options.png',fullPage:true});
await page.locator('[data-select]').first().click();await page.locator('#confirm').waitFor();
await page.locator('#save-exit').click();await page.getByRole('button',{name:'Resume request',exact:true}).waitFor();
await page.reload();await page.locator('#confirm').waitFor();
await page.locator('#chat-input').fill('under ₹400 tomorrow morning');await page.locator('#chat-input').press('Enter');
await page.locator('[data-select]').first().waitFor();
if(await page.locator('#confirm').count())throw Error('Stale confirmation remained');
await page.locator('[data-select]').first().click();await page.locator('#confirm').click();await page.locator('.success').waitFor();
await page.reload();await page.locator('.success').waitFor();
await page.screenshot({path:'docs/screenshots/success.png',fullPage:true});
await page.locator('#new-task').click();await page.locator('#sample').click();await page.locator('[name="budget"]').fill('100');await page.getByRole('button',{name:'Find available appointments'}).click();await page.getByRole('heading',{name:'No matching appointments'}).waitFor();
await page.setViewportSize({width:390,height:844});
await page.locator('[data-edit]').first().click();await page.locator('[name="budget"]').fill('500');await page.getByRole('button',{name:'Find available appointments'}).click();await page.locator('.provider').first().waitFor();
await page.screenshot({path:'docs/screenshots/mobile.png',fullPage:true});
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
await page.locator('#mcp-settings').click();await page.locator('#mint-token').click();await page.locator('#token-result textarea').waitFor();
if(!(await page.locator('#token-result textarea').inputValue()).length)throw Error('Missing MCP token');
await page.locator('#revoke-token').click();await page.getByText('Token revoked.',{exact:true}).waitFor();
if(errors.length)throw Error(errors.join('\n'));
console.log('PASS UI: creation, options, selection, pause/reload/resume, revision invalidation, confirmation, persisted booking, empty results, mobile width, MCP token issue/revoke, no page errors.');
await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
